// Browser QA against the same disposable MySQL database used by CI.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createPool,migrate } from '../src/db.js';
import { createApp } from '../src/app.js';
import { hashPassword } from '../src/security.js';
if(process.env.CRM_TEST_MYSQL!=='1')throw new Error('Browser QA requires disposable MySQL test configuration.');
const config={database:{host:'127.0.0.1',port:Number(process.env.CRM_TEST_DB_PORT||3306),user:'root',password:process.env.CRM_TEST_DB_PASSWORD||'test-only',database:'cosmiccrm_test'},sessionSecret:'browser-test-secret-'.repeat(4),secureCookies:false,trustProxy:false,publicUrl:'http://127.0.0.1',currency:'USD',appName:'CosmicCRM'};
const pool=createPool(config);let server,browser;
try {
  await migrate(pool);
  const hash=await hashPassword('Browser smoke password 123');
  await pool.execute("INSERT INTO users(name,email,role,password_hash) VALUES ('Browser Admin','browser@test.example','owner',?) ON DUPLICATE KEY UPDATE password_hash=VALUES(password_hash),active=1,role='owner'",[hash]);
  server=createApp({pool,config}).listen(0,'127.0.0.1');await new Promise(resolve=>server.on('listening',resolve));
  config.publicUrl='http://127.0.0.1:'+server.address().port;
  browser=await chromium.launch();
  const context=await browser.newContext({viewport:{width:1440,height:1080}});
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(config.publicUrl);
  await page.getByLabel('Email address').fill('browser@test.example');
  await page.getByLabel('Password',{exact:true}).fill('Browser smoke password 123');
  await page.getByRole('button',{name:'Sign in'}).click();
  await page.getByRole('heading',{name:'Welcome back, Browser.'}).waitFor();
  await mkdir('test-results',{recursive:true});
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
  await page.locator('nav').getByRole('link',{name:'Companies',exact:true}).click();
  await page.getByRole('button',{name:'Add company'}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Name *',{exact:true}).fill('Browser QA Company');
  await dialog.getByRole('button',{name:'Save record',exact:true}).click();
  await dialog.getByRole('heading',{name:'Browser QA Company',exact:true}).waitFor();
  await dialog.getByLabel('New note').fill('A tested customer conversation.');
  await dialog.getByRole('button',{name:'Add note',exact:true}).click();
  await dialog.getByText('A tested customer conversation.',{exact:false}).waitFor();
  await dialog.getByRole('button',{name:'Close',exact:true}).click();
  await page.locator('nav').getByRole('link',{name:'Quotes',exact:true}).click();
  await page.getByRole('button',{name:'Add quote'}).click();
  await dialog.getByLabel('Name *',{exact:true}).fill('Browser QA Quote');
  await dialog.getByLabel('Status',{exact:true}).selectOption('accepted');
  await dialog.getByLabel('Tax Rate *',{exact:true}).fill('10');
  await dialog.getByLabel('Item description').fill('Managed services');
  await dialog.getByLabel('Quantity',{exact:true}).fill('2');
  await dialog.getByLabel('Unit price',{exact:true}).fill('50');
  await dialog.getByRole('button',{name:'Save record',exact:true}).click();
  await dialog.getByRole('button',{name:'Create invoice'}).waitFor();
  await dialog.getByRole('button',{name:'Create invoice'}).click();
  await dialog.getByText('Invoices / #',{exact:false}).waitFor();
  assert.match(await page.locator('#totals').textContent(),/110\.00/);
  await page.screenshot({path:'test-results/invoice-desktop.png',fullPage:true});
  await dialog.getByRole('button',{name:'Close',exact:true}).click();
  await page.locator('nav').getByRole('link',{name:'Overview',exact:true}).click();
  await page.getByRole('heading',{name:'Welcome back, Browser.'}).waitFor();
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('#sidebar').getBoundingClientRect().right<=1);
  await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile dashboard should not overflow horizontally.');
  await page.getByRole('button',{name:'Toggle navigation'}).click();
  await page.locator('nav').getByRole('link',{name:'Contacts',exact:true}).click();
  await page.getByRole('button',{name:'Add contact'}).waitFor();
  await page.waitForFunction(()=>document.querySelector('#sidebar').getBoundingClientRect().right<=1);
  await page.screenshot({path:'test-results/contacts-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1080});
  await page.locator('nav').getByRole('link',{name:'Team',exact:true}).click();
  await page.getByRole('button',{name:'Add owner'}).click();
  await dialog.getByRole('heading',{name:'Create owner account',exact:true}).waitFor();
  assert.equal(await dialog.locator('select[name=role]').inputValue(),'owner');
  await dialog.getByLabel('Name',{exact:true}).fill('Browser QA Owner');
  await dialog.getByLabel('Email',{exact:true}).fill('browser-qa-owner@test.example');
  await dialog.getByLabel('Password',{exact:true}).fill('Browser QA owner password 123');
  await dialog.getByRole('button',{name:'Save account',exact:true}).click();
  await page.getByRole('cell',{name:'Browser QA Owner',exact:true}).waitFor();
  await page.screenshot({path:'test-results/owner-team-desktop.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Browser smoke passed: owner sign in, company creation, notes, quote → invoice, totals, desktop/mobile navigation and owner account creation.');
} finally {
  if(browser)await browser.close();
  if(server)await new Promise(resolve=>server.close(resolve));
  await pool.end();
}
